namespace odl3d.Renderer;

/// <summary>
/// Represents the different step modes that can be used in rendering operations.
/// </summary>
public enum StepMode
{
    /// <summary>
    /// The step mode is per vertex.
    /// </summary>
    PerVertex,
    /// <summary>
    /// The step mode is per instance.
    /// </summary>
    PerInstance
}