namespace odl3d.Renderer;

/// <summary>
/// Represents the different store actions that can be used in rendering operations.
/// </summary>
public enum StoreAction
{
    /// <summary>
    /// The store action is to not care about the result.
    /// </summary>
    DontCare,
    /// <summary>
    /// The store action is to store the result.
    /// </summary>
    Store
}