namespace odl3d.Renderer;

/// <summary>
/// Represents the different index formats that can be used in rendering operations.
/// </summary>
public enum IndexFormat
{
    /// <summary>
    /// Represents a 16-bit unsigned integer index format.
    /// </summary>
    UInt16,
    /// <summary>
    /// Represents a 32-bit unsigned integer index format.
    /// </summary>
    UInt32
}